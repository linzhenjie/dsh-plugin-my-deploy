#!/usr/bin/env node
/**
 * Generate the two data chunks of the my-deploy browser bundle.
 *
 * The browser half is split into real files served by the Harness bundle route.
 * Two of them are *content* chunks generated from source files:
 *
 *   src/config/zh.json + en.json  ->  client.i18n.js
 *   src/styles.css                ->  client.styles.js
 *
 * Everything else is hand-written and shipped as-is, which this script verifies.
 *
 * Usage:
 *   node build.mjs           write the generated chunks
 *   node build.mjs --check   fail when a generated chunk is stale
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const checkOnly = process.argv.includes('--check');

/** Bundle identity; must match the package name and the sidebar/panel id. */
const PLUGIN_ID = 'my-deploy';

/** Hand-written chunks; the build only parses and sanity-checks them. */
const HAND_WRITTEN = ['client.utils.js', 'client.model.js', 'client.data.js', 'client.ui.js', 'client.page.js'];

/** Chunk names the entry must resolve, so a renamed file cannot silently break. */
const EXPECTED_CHUNKS = [...HAND_WRITTEN, 'client.i18n.js', 'client.styles.js'];

/** The Harness loader only treats `client.<name>.js` as a package-local chunk. */
const CHUNK_NAME = /^client\.[A-Za-z0-9][A-Za-z0-9._-]*\.js$/;

const errors = [];

/** Wrap one module body into a chunk registration. */
function wrap(banner, chunkFile, body) {
  return `/**\n * ${banner}\n *\n * GENERATED by build.mjs — do not edit.\n */\nwindow.__ModuleLoader__.load({\n  id: '${PLUGIN_ID}',\n  chunk: '${chunkFile}',\n  factory() {\n    return () => (${body});\n  },\n});\n`;
}

async function readText(relativePath) {
  try {
    return await readFile(join(root, relativePath), 'utf8');
  } catch (error) {
    errors.push(`${relativePath}: cannot read (${error.message})`);
    return '';
  }
}

async function readJson(relativePath) {
  const raw = await readText(relativePath);
  try {
    return JSON.parse(raw);
  } catch (error) {
    errors.push(`${relativePath}: invalid JSON (${error.message})`);
    return {};
  }
}

/** Locale dictionaries must carry the same non-empty keys. */
function validateLocales(zh, en) {
  for (const [name, dictionary] of [
    ['zh', zh],
    ['en', en],
  ]) {
    for (const [key, value] of Object.entries(dictionary)) {
      if (typeof value !== 'string' || value.trim() === '') errors.push(`locale ${name}: "${key}" must be a non-empty string`);
    }
  }
  const zhKeys = Object.keys(zh).sort();
  const enKeys = Object.keys(en).sort();
  if (JSON.stringify(zhKeys) !== JSON.stringify(enKeys)) {
    const missingInEn = zhKeys.filter((key) => !(key in en));
    const missingInZh = enKeys.filter((key) => !(key in zh));
    errors.push(
      `locales disagree (missing in en: ${missingInEn.join(', ') || 'none'}; missing in zh: ${missingInZh.join(', ') || 'none'})`,
    );
  }
}

/** Parse-only gate for every emitted or hand-written script. */
function validateScript(relativePath, source) {
  try {
    new Function(source);
  } catch (error) {
    errors.push(`${relativePath}: does not parse (${error.message})`);
  }
}

async function generate() {
  const zh = await readJson('src/config/zh.json');
  const en = await readJson('src/config/en.json');
  const css = await readText('src/styles.css');
  validateLocales(zh, en);

  const i18n = wrap(
    'UI dictionaries, generated from src/config/zh.json and src/config/en.json.',
    'client.i18n.js',
    `{ zh: ${JSON.stringify(zh, null, 6)}, en: ${JSON.stringify(en, null, 6)} }`,
  );
  const styles = wrap('Page styles, generated from src/styles.css.', 'client.styles.js', `{ css: ${JSON.stringify(css)} }`);

  validateScript('client.i18n.js', i18n);
  validateScript('client.styles.js', styles);

  return { i18n, styles };
}

/** Verify the hand-written chunks and the entry's wiring. */
async function validateHandWritten() {
  for (const file of HAND_WRITTEN) {
    if (!CHUNK_NAME.test(file)) errors.push(`${file}: a chunk file must be named client.<name>.js`);
    const source = await readText(file);
    if (source.trim() === '') continue;
    validateScript(file, source);
    if (!source.includes(`chunk: '${file}'`)) errors.push(`${file}: must register with chunk: '${file}'`);
    if (!source.includes(`id: '${PLUGIN_ID}'`)) errors.push(`${file}: must register with id: '${PLUGIN_ID}'`);
    if (/^\s*(import|export)\b/m.test(source)) errors.push(`${file}: a chunk cannot be an ES module`);
  }

  const entry = await readText('client.js');
  validateScript('client.js', entry);
  for (const file of EXPECTED_CHUNKS) {
    if (!entry.includes(`'${file}'`)) errors.push(`client.js: does not load ${file}`);
  }
}

const { i18n, styles } = await generate();
await validateHandWritten();

if (errors.length > 0) {
  process.stderr.write(`build: ${errors.length} problem(s):\n${errors.map((line) => `  - ${line}`).join('\n')}\n`);
  process.exit(1);
}

const outputs = [
  ['client.i18n.js', i18n],
  ['client.styles.js', styles],
];

if (checkOnly) {
  for (const [file, expected] of outputs) {
    let current = '';
    try {
      current = await readFile(join(root, file), 'utf8');
    } catch (error) {
      process.stderr.write(`build: ${file} is missing (${error.message})\n`);
      process.exit(1);
    }
    if (current !== expected) {
      process.stderr.write(`build: ${file} is stale — run \`node build.mjs\`\n`);
      process.exit(1);
    }
  }
  process.stdout.write('build: generated chunks are up to date\n');
} else {
  for (const [file, source] of outputs) {
    await writeFile(join(root, file), source, 'utf8');
    process.stdout.write(`build: wrote ${file} (${Buffer.byteLength(source)} bytes)\n`);
  }
}
